import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
const base = process.env.CITY_BASE || 'http://127.0.0.1:8791';
const browser=await chromium.launch({headless:true});
try {
const page=await browser.newPage({viewport:{width:1000,height:800}});const errors=[];const wavs=[];
page.on('pageerror',e=>errors.push(e.message));page.on('response',r=>{if(r.url().endsWith('.wav'))wavs.push([r.url(),r.status()]);});
await page.goto(`${base}/johannesburg.html?audioDebug`);
await page.waitForFunction(()=>window.__johannesburg?.city.trainRoot.children.length===19);
assert.equal(await page.evaluate(()=>window.__johannesburg.sound.diagnostics.context),'not-created');
await page.getByRole('button',{name:'Sound off',exact:true}).click();
await page.waitForFunction(()=>window.__johannesburg.sound.diagnostics.ready);
await page.waitForTimeout(600);
console.log('RUNNING',await page.evaluate(()=>window.__johannesburg.sound.diagnostics));
assert.equal(wavs.length,8);assert.ok(wavs.every(x=>x[1]===200));
await page.locator('[data-train-audio] summary').click();
await page.getByRole('button',{name:'Bridge',exact:true}).click();
await page.waitForFunction(()=>window.__johannesburg.sound.diagnostics.state.environment==='BRIDGE');
await page.getByRole('button',{name:'Route',exact:true}).click();
await page.getByRole('button',{name:'Pause',exact:true}).click();
await page.waitForFunction(()=>window.__johannesburg.sound.diagnostics.context==='suspended');
await page.getByRole('button',{name:'Play',exact:true}).click();
await page.waitForFunction(()=>window.__johannesburg.sound.diagnostics.context==='running');
await page.evaluate(()=>{ window.__johannesburg.dispose(); window.__johannesburg.dispose(); });
await page.waitForFunction(()=>window.__johannesburg.sound.diagnostics.context==='closed');
assert.equal(await page.locator('[data-train-audio]').count(),0);assert.deepEqual(errors,[]);
console.log('PASS: gesture startup, 8 wavs, bridge override, pause, resume, disposal, no page errors');
await page.goto(`${base}/animation?audioDebug`);
await page.waitForFunction(()=>document.querySelector('main')?.dataset.ready === 'true' && window.__railScene, null, {timeout:120000});
assert.equal(await page.evaluate(()=>window.__railScene.sound.diagnostics.context), 'not-created');
await page.getByRole('button',{name:/sound off/i}).click();
await page.waitForFunction(()=>window.__railScene.sound.diagnostics.ready);
await page.getByRole('button',{name:'Start journey',exact:true}).click();
await page.waitForFunction(()=>window.__railScene.sound.diagnostics.state?.speedKph > 1);
assert.equal(await page.evaluate(()=>window.__railScene.sound.diagnostics.context),'running');
await page.getByRole('button',{name:'Pause journey',exact:true}).click();
await page.waitForFunction(()=>window.__railScene.sound.diagnostics.context==='suspended');
assert.deepEqual(errors,[]);
console.log('PASS: Pretoria gesture startup, moving audio, pause; no page errors');
} finally {await browser.close();}

import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
const base=process.env.CITY_BASE||'http://127.0.0.1:8791';
const browser=await chromium.launch({headless:true});
const errors=[],external=[];
await mkdir('evidence/corridor',{recursive:true});
try {
  const page=await browser.newPage({viewport:{width:1280,height:900},reducedMotion:'reduce',serviceWorkers:'block'});
  page.on('pageerror',e=>errors.push(e.message));
  page.on('request',r=>{if(!r.url().startsWith(base)&&!r.url().startsWith('data:'))external.push(r.url());});
  await page.goto(`${base}/corridor`);
  await page.getByRole('button',{name:'Travel',exact:true}).waitFor();
  await page.waitForFunction(()=>document.querySelector('.corridor-canvas')?.dataset.ready==='true',null,{timeout:90000});
  await page.screenshot({path:'evidence/corridor/pretoria.png'});
  const slider=page.getByRole('slider',{name:'Corridor distance'});
  await slider.fill('35000');await slider.dispatchEvent('change');
  await page.waitForTimeout(250);
  await page.screenshot({path:'evidence/corridor/midpoint.png'});
  assert.equal(await page.locator('.corridor-canvas').getAttribute('data-chunks'),'4');
  await page.getByRole('button',{name:'Travel',exact:true}).click();await page.waitForTimeout(1500);
  await page.getByRole('button',{name:'Sound off',exact:true}).click();
  await page.getByRole('button',{name:'Sound on',exact:true}).waitFor({timeout:30000});
  await page.getByRole('button',{name:'Sound on',exact:true}).click();
  await page.getByRole('button',{name:'Follow train',exact:true}).click();
  await page.getByRole('button',{name:'Pause',exact:true}).click();
  const moved=Number(await slider.inputValue());assert.ok(moved>35000);
  await page.waitForTimeout(300);assert.equal(Number(await slider.inputValue()),moved);
  await page.getByRole('button',{name:'Park Station',exact:true}).click();
  await page.waitForTimeout(250);await page.screenshot({path:'evidence/corridor/johannesburg.png'});
  assert.ok(Number(await slider.inputValue())>69000);
  await page.getByRole('heading',{name:'Welcome to Park Station'}).waitFor();
  assert.deepEqual(external,[],'3D corridor must not require any external tile or asset requests');
  await page.getByRole('button',{name:'Satellite / map',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('[data-testid="journey-route-source"]')?.textContent.includes('osm mapped connected candidate'),null,{timeout:60000});
  await page.locator('.journey-map-loading').waitFor({state:'hidden',timeout:60000});
  await page.waitForTimeout(2500);
  await page.screenshot({path:'evidence/corridor/map.png'});
  await page.getByRole('button',{name:'3D journey',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('.corridor-canvas')?.dataset.ready==='true',null,{timeout:90000});
  await page.waitForTimeout(200);assert.ok(Number(await slider.inputValue())>69000,'map handoff must preserve chainage');
  await page.setViewportSize({width:390,height:844});await page.waitForTimeout(200);
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.screenshot({path:'evidence/corridor/mobile.png'});
  await slider.fill('18000');await slider.dispatchEvent('change');
  await page.reload();
  await page.waitForFunction(()=>document.querySelector('.corridor-canvas')?.dataset.ready==='true',null,{timeout:90000});
  await page.waitForTimeout(250);
  assert.ok(Math.abs(Number(await slider.inputValue())-18000)<20,'reload resumes saved position');
  assert.equal(await page.getByRole('button',{name:'Travel',exact:true}).isVisible(),true,'reload stays paused');
  assert.deepEqual(errors,[]);
  await writeFile('evidence/corridor/checks.json',JSON.stringify({base,errors,threeDExternalRequests:0,checks:['travel','pause','seek','four bounded chunks','map handoff','mobile overflow']},null,2));
  console.log('Corridor checks passed');
}finally{await browser.close();}
